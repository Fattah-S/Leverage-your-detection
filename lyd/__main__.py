"""Command line.

    python3 -m lyd demo                       two simulated weeks (review policy plays the engineer)
    python3 -m lyd demo --review manual       same, but proposals wait for you in the review queue
    python3 -m lyd serve                      web dashboard on http://127.0.0.1:8765
    python3 -m lyd chat                       chat in the terminal (or --ask "question")
    python3 -m lyd advisory                   write the monthly use-case advisory
    python3 -m lyd prs open [--live]          proposals -> GitHub pull requests (dry run by default)
    python3 -m lyd prs sync                   merged / closed pull requests -> decisions
    python3 -m lyd routes                     which agent listens to which event

Add --llm ollama [--model llama3.2] to any command to let a local model write the text.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from . import advisory, attack
from .llm import get as get_llm
from .platform import ROOT, Platform, load_json
from .trace import write as write_trace

DEFAULT_OUT = ROOT / "docs" / "demo"


def platform(args, review_mode=None, fresh=False) -> Platform:
    return Platform(Path(args.out), get_llm(args.llm, args.model), fresh=fresh, review_mode=review_mode)


def write_advisory(p: Platform, period: str = "October 2026") -> Path:
    f = p.out / "monthly-advisory.md"
    f.write_text(advisory.markdown(p.ctx, period))
    return f


def cmd_demo(args) -> None:
    p = platform(args, review_mode=args.review, fresh=True)
    intel = load_json(ROOT / "samples" / "intel.json")
    stats = load_json(ROOT / "samples" / "alert_stats.json")
    results = [p.run_week(w, intel[w], stats[w]) for w in ("week-1", "week-2")]
    header = (f"# Run trace\n\nGenerated by `python3 -m lyd demo` · {len(p.bus.all())} events · "
              f"{len(p.orch.nodes)} agents · ATT&CK v{attack.load()['attack_release']} · LLM: {p.ctx.llm.name} · "
              f"review: {p.ctx.review_mode}\n\n"
              "> Placeholder use cases and placeholder intel. This proves the agents are linked and the "
              "event flow works end to end; it does not measure detection quality.")
    (p.out / "run-trace.md").write_text(write_trace(p.bus, p.orch.routing_table(), header))
    write_advisory(p)
    p.save()
    print(f"Agents: {', '.join(n.name for n in p.orch.nodes)}")
    print(f"Events processed: {len(p.bus.all())}")
    for r in results:
        print(f"{r['week']}: priority coverage {r['before']}% -> {r['after']}%")
    status: dict[str, int] = {}
    for pr in p.ctx.proposals.values():
        status[pr["status"]] = status.get(pr["status"], 0) + 1
    print("Proposals: " + ", ".join(f"{v} {k.replace('_', ' ')}" for k, v in sorted(status.items())))
    print(f"Outputs in {p.out}: run-trace.md, week-1/report.md, week-2/report.md, monthly-advisory.md")
    print("Next: python3 -m lyd serve   (dashboard)   or   python3 -m lyd chat")


def cmd_serve(args) -> None:
    from .web import serve
    p = platform(args, review_mode="manual")
    serve(p, args.port)


def cmd_chat(args) -> None:
    from .chat import Chat, repl
    p = platform(args, review_mode="manual")
    if args.ask:
        print(Chat(p).ask(args.ask))
    else:
        repl(p)


def cmd_advisory(args) -> None:
    p = platform(args)
    f = write_advisory(p, args.period)
    print(f.read_text())


def cmd_prs(args) -> None:
    from . import github_pr
    p = platform(args, review_mode="manual")
    if args.action == "open":
        res = github_pr.open_prs(p, args.repo, args.base, dry_run=not args.live)
        if not res:
            print("No proposals waiting for review. Ask the chat to build a use case, or run: python3 -m lyd demo --review manual")
        for r in res:
            print(f"{r['proposal']}: " + (f"dry run, preview in {r['file']}" if r.get("dry_run") else f"opened #{r['number']} {r['url']}"))
        if res and not args.live:
            print("Dry run only. Add --live to push branches and open the pull requests.")
    else:
        res = github_pr.sync_prs(p, args.repo)
        if not res:
            print("No decisions on GitHub yet (pull requests still open).")
        for r in res:
            print(f"{r['proposal']}: {r['decision']}" + (f" ({r['reason']})" if r.get("reason") else ""))


def cmd_routes(args) -> None:
    p = platform(args)
    for t, ns in p.orch.routing_table().items():
        print(f"{t:28} -> {', '.join(ns)}")


def main() -> None:
    ap = argparse.ArgumentParser(prog="lyd", description="Leverage your detection: multi-agent prototype")
    sub = ap.add_subparsers(dest="cmd", required=True)

    def common(sp):
        sp.add_argument("--llm", choices=["mock", "ollama"], default="mock")
        sp.add_argument("--model", default="llama3.2", help="Ollama model name")
        sp.add_argument("--out", default=str(DEFAULT_OUT), help="platform state folder")
        return sp

    d = common(sub.add_parser("demo", help="run two simulated weeks"))
    d.add_argument("--review", choices=["auto", "manual"], default="auto")
    d.set_defaults(func=cmd_demo)
    s = common(sub.add_parser("serve", help="web dashboard"))
    s.add_argument("--port", type=int, default=8765)
    s.set_defaults(func=cmd_serve)
    c = common(sub.add_parser("chat", help="chat with the platform"))
    c.add_argument("--ask", help="ask one question and exit")
    c.set_defaults(func=cmd_chat)
    a = common(sub.add_parser("advisory", help="monthly use-case advisory"))
    a.add_argument("--period", default="October 2026")
    a.set_defaults(func=cmd_advisory)
    g = common(sub.add_parser("prs", help="GitHub pull requests"))
    g.add_argument("action", choices=["open", "sync"])
    g.add_argument("--repo", default="Fattah-S/Leverage-your-detection")
    g.add_argument("--base", default="main")
    g.add_argument("--live", action="store_true", help="really push branches and open pull requests")
    g.set_defaults(func=cmd_prs)
    r = common(sub.add_parser("routes", help="print the routing table"))
    r.set_defaults(func=cmd_routes)
    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
