"""Command line.

    python3 -m lyd demo                      # two simulated weeks, mock LLM
    python3 -m lyd demo --llm ollama         # same, text written by a local Ollama model
    python3 -m lyd routes                    # show which agent listens to which event
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

from . import attack
from .bus import EventBus
from .llm import get as get_llm
from .memory import Memory
from .nodes import all_nodes
from .nodes.base import Context
from .nodes.coverage import score
from .orchestrator import Orchestrator
from .trace import write as write_trace

ROOT = Path(__file__).resolve().parents[1]


def load_json(path: Path) -> dict:
    return json.loads(path.read_text())


def build(out: Path, llm, fresh: bool = True):
    if fresh and out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)
    bus = EventBus(out / "events.sqlite")
    library = {u["id"]: u for u in load_json(ROOT / "samples" / "use_cases.json")["use_cases"]}
    ctx = Context(profile=load_json(ROOT / "config" / "profile.json"), library=library,
                  intel_inbox=[], alert_stats=[], review_policy=load_json(ROOT / "config" / "review_policy.json"),
                  memory=Memory(out / "memory.jsonl"), llm=llm, out_dir=out)
    orch = Orchestrator(bus, ctx, all_nodes(bus))
    return bus, ctx, orch


def run_week(bus: EventBus, ctx: Context, orch: Orchestrator, week: str, intel: list, stats: list) -> dict:
    ctx.week, ctx.intel_inbox, ctx.alert_stats = week, intel, stats
    baseline = score(ctx)
    first_event = (bus.all() or [{"id": 0}])[-1]["id"]
    bus.publish("tick", "scheduler", {"week": week})
    orch.run()
    bus.publish("report_requested", "scheduler", {"week": week, "baseline": baseline, "first_event": first_event})
    orch.run()
    return {"week": week, "before": baseline["pct"], "after": score(ctx)["pct"]}


def cmd_demo(args) -> None:
    out = Path(args.out)
    llm = get_llm(args.llm, args.model)
    bus, ctx, orch = build(out, llm)
    intel = load_json(ROOT / "samples" / "intel.json")
    stats = load_json(ROOT / "samples" / "alert_stats.json")
    results = [run_week(bus, ctx, orch, w, intel[w], stats[w]) for w in ("week-1", "week-2")]

    header = (f"# Run trace\n\nGenerated by `python3 -m lyd demo` · {len(bus.all())} events · "
              f"{len(orch.nodes)} agents · ATT&CK v{attack.load()['attack_release']} · LLM: {llm.name}\n\n"
              "> Placeholder use cases and placeholder intel. This proves the agents are linked and the "
              "event flow works end to end; it does not measure detection quality.")
    (out / "run-trace.md").write_text(write_trace(bus, orch.routing_table(), header))
    (out / "proposals.json").write_text(json.dumps(ctx.proposals, indent=1))

    print(f"Agents: {', '.join(n.name for n in orch.nodes)}")
    print(f"Events processed: {len(bus.all())}")
    for r in results:
        print(f"{r['week']}: priority coverage {r['before']}% -> {r['after']}%")
    status = {}
    for p in ctx.proposals.values():
        status[p["status"]] = status.get(p["status"], 0) + 1
    print("Proposals: " + ", ".join(f"{v} {k}" for k, v in sorted(status.items())))
    print(f"Outputs: {out}/run-trace.md, {out}/week-1/report.md, {out}/week-2/report.md, navigator layers")


def cmd_routes(args) -> None:
    _, _, orch = build(Path(args.out) / "_routes", get_llm("mock"))
    for t, ns in orch.routing_table().items():
        print(f"{t:28} -> {', '.join(ns)}")
    shutil.rmtree(Path(args.out) / "_routes", ignore_errors=True)


def main() -> None:
    ap = argparse.ArgumentParser(prog="lyd", description="Leverage your detection: agent wiring prototype")
    sub = ap.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("demo", help="run two simulated weeks")
    d.add_argument("--llm", choices=["mock", "ollama"], default="mock")
    d.add_argument("--model", default="llama3.2", help="Ollama model name")
    d.add_argument("--out", default="docs/demo")
    d.set_defaults(func=cmd_demo)
    r = sub.add_parser("routes", help="print the routing table")
    r.add_argument("--out", default="docs/demo")
    r.set_defaults(func=cmd_routes)
    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
